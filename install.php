require_once __DIR__ . '/bootstrap.php';

$db = SCP_Database::getInstance();

// Check if already installed (lock installer immediately once config/database.php is configured)
$alreadyInstalled = false;
if (defined('SCP_DB_HOST') && defined('SCP_DB_NAME') && SCP_DB_NAME !== '' && SCP_DB_NAME !== 'your_database_name') {
    $alreadyInstalled = true;
} elseif ($db->isConfigured()) {
    $alreadyInstalled = true;
}

if ($alreadyInstalled) {
    header('Location: index.php?page=login');
    exit;
}

// Environment pre-flight check
$requirements = array(
    'php' => array(
        'label' => 'PHP Version >= 7.4.0 (Current: ' . PHP_VERSION . ')',
        'pass'  => version_compare(PHP_VERSION, '7.4.0', '>=')
    ),
    'pdo' => array(
        'label' => 'PDO MySQL Driver Extension (pdo_mysql)',
        'pass'  => extension_loaded('pdo_mysql')
    ),
    'openssl' => array(
        'label' => 'OpenSSL Security Extension',
        'pass'  => extension_loaded('openssl')
    ),
    'curl' => array(
        'label' => 'cURL HTTP Client Extension',
        'pass'  => extension_loaded('curl')
    ),
    'config_writable' => array(
        'label' => 'Writable Config Directory (config/)',
        'pass'  => is_writable(__DIR__ . '/config') || (!file_exists(__DIR__ . '/config') && is_writable(__DIR__))
    ),
);
$allPass = true;
foreach ($requirements as $req) {
    if (!$req['pass']) {
        $allPass = false;
        break;
    }
}

$detectedUrl = SCP_Security::getBaseUrl();
$csrfToken = SCP_Security::getCsrfToken();
$error = '';
$success = '';

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    if (!SCP_Security::verifyCsrfToken($_POST['csrf_token'] ?? '')) {
        $error = 'Security session expired. Please refresh the page and try again.';
    } else {
        $dbHost      = trim($_POST['db_host'] ?? 'localhost');
        $dbPort      = trim($_POST['db_port'] ?? '3306');
        $dbName      = trim($_POST['db_name'] ?? '');
        $dbUser      = trim($_POST['db_user'] ?? '');
        $dbPass      = $_POST['db_pass'] ?? '';
        $companyName = trim($_POST['company_name'] ?? 'Cloud Portal');
        $siteTitle   = trim($_POST['site_title'] ?? 'Enterprise Cloud Hosting, Domains & Client Portal');
        $siteUrl     = rtrim(trim($_POST['site_url'] ?? $detectedUrl), '/');
        $adminEmail  = strtolower(trim($_POST['admin_email'] ?? ''));
        $adminPass   = $_POST['admin_pass'] ?? '';
        $adminFn     = trim($_POST['admin_first_name'] ?? 'Admin');
        $adminLn     = trim($_POST['admin_last_name'] ?? 'User');

        if (empty($dbHost) || empty($dbName) || empty($dbUser) || empty($adminEmail) || empty($adminPass)) {
            $error = 'Please fill in all required database and administrator fields.';
        } elseif (!filter_var($adminEmail, FILTER_VALIDATE_EMAIL)) {
            $error = 'Please enter a valid administrator email address.';
        } elseif (!SCP_Security::validateHttpUrl($siteUrl)) {
            $error = 'Please enter a valid HTTP/HTTPS Site Base URL.';
        } elseif (strlen($adminPass) < 8) {
            $error = 'Administrator password must be at least 8 characters long.';
        } else {
            try {
                $dsn = sprintf('mysql:host=%s;port=%s;dbname=%s;charset=utf8mb4', $dbHost, $dbPort, $dbName);
                $pdo = new PDO($dsn, $dbUser, $dbPass, array(
                    PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
                    PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                    PDO::ATTR_EMULATE_PREPARES   => false,
                ));

                // Write config/database.php safely
                $configContent = "<?php\n"
                    . "/**\n * MySQL / MariaDB Database Configuration (Generated by Setup Wizard)\n */\n\n"
                    . "if (!defined('SCP_APP_INIT')) { http_response_code(403); exit('Direct access forbidden.'); }\n\n"
                    . "define('SCP_DB_HOST', " . var_export($dbHost, true) . ");\n"
                    . "define('SCP_DB_PORT', " . var_export($dbPort, true) . ");\n"
                    . "define('SCP_DB_NAME', " . var_export($dbName, true) . ");\n"
                    . "define('SCP_DB_USER', " . var_export($dbUser, true) . ");\n"
                    . "define('SCP_DB_PASS', " . var_export($dbPass, true) . ");\n"
                    . "define('SCP_DB_CHARSET', 'utf8mb4');\n"
                    . "define('SCP_SITE_URL', " . var_export($siteUrl, true) . ");\n";

                file_put_contents(__DIR__ . '/config/database.php', $configContent);

                if (!defined('SCP_DB_HOST')) {
                    define('SCP_DB_HOST', $dbHost);
                    define('SCP_DB_PORT', $dbPort);
                    define('SCP_DB_NAME', $dbName);
                    define('SCP_DB_USER', $dbUser);
                    define('SCP_DB_PASS', $dbPass);
                    define('SCP_DB_CHARSET', 'utf8mb4');
                    define('SCP_SITE_URL', $siteUrl);
                }

                // Copy sample configuration files if custom ones do not exist yet
                $credSample = __DIR__ . '/config/credentials.sample.php';
                $credActual = __DIR__ . '/config/credentials.php';
                if (!file_exists($credActual) && file_exists($credSample)) {
                    @copy($credSample, $credActual);
                }

                $mailSample = __DIR__ . '/config/mail.sample.php';
                $mailActual = __DIR__ . '/config/mail.php';
                if (!file_exists($mailActual) && file_exists($mailSample)) {
                    @copy($mailSample, $mailActual);
                }

                // Ensure assets/uploads exists and is secured
                $uploadDir = __DIR__ . '/assets/uploads';
                if (!is_dir($uploadDir)) {
                    @mkdir($uploadDir, 0755, true);
                }
                $htPath = $uploadDir . '/.htaccess';
                if (!file_exists($htPath)) {
                    @file_put_contents($htPath, "<FilesMatch \"\\.(php|phtml|php3|php4|php5|php7|phps)$\">\n    Deny from all\n</FilesMatch>\nOptions -ExecCGI\n");
                }

                // Install database schema & defaults
                $db->installSchema();

                // Set portal custom identity
                if (!empty($companyName)) {
                    $db->setSetting('company_name', $companyName);
                }
                if (!empty($siteTitle)) {
                    $db->setSetting('site_title', $siteTitle);
                }

                // Create initial Administrator account
                $auth = new SCP_Auth();
                $stripe = new SCP_StripeService();
                $reg = $auth->register($adminEmail, $adminPass, $adminFn, $adminLn, $companyName ?: 'Cloud Portal', $stripe, 'admin');

                if (!empty($reg['success'])) {
                    session_regenerate_id(true);
                    $_SESSION['scp_user_id'] = (int)$reg['user_id'];
                    $_SESSION['scp_user_role'] = 'admin';
                    $db->logActivity((int)$reg['user_id'], 'portal_installed', 'Cloud Portal installation completed successfully.');
                    header('Location: index.php?page=admin&installed=1');
                    exit;
                } else {
                    $error = $reg['error'] ?? 'Failed to create administrator account.';
                }
            } catch (Exception $e) {
                $error = 'Database Connection Error: ' . $e->getMessage();
            }
        }
    }
}
